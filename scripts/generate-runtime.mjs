import assert from 'node:assert/strict';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const root = fileURLToPath(new URL('../', import.meta.url));
const args = process.argv.slice(2);
assert.ok(
  args.length === 0 || (args.length === 1 && args[0] === '--check'),
  'Usage: generate-runtime.mjs [--check]',
);
const result = await build({
  absWorkingDir: root,
  entryPoints: ['packages/runtime-sdk/src/bootstrap.ts'],
  bundle: true,
  format: 'iife',
  globalName: '__ArtifreeBootstrap',
  target: 'es2022',
  legalComments: 'none',
  write: false,
});
const output = `/* Generated by npm run generate:runtime; do not edit. */\n${result.outputFiles[0].text}`;
// The bundle is embedded in an HTML script element. HTML ends a script at
// this sequence even when JavaScript would treat it as a string or comment.
assert.ok(!output.toLowerCase().includes('</script'), 'Unsafe script bundle.');
const path = new URL(
  '../crates/artifree-server/src/runtime_bootstrap.generated',
  import.meta.url,
);
if (args.includes('--check')) {
  assert.equal(
    await readFile(path, 'utf8'),
    output,
    'Generated runtime drift.',
  );
  console.log('Verified the generated runtime bootstrap.');
} else {
  await writeFile(path, output);
  console.log('Generated the runtime bootstrap.');
}
