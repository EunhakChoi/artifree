import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';

// Only public Unicode data is an input. Pin the bytes as well as the release;
// compiler/ICU upgrades must never change which stored members are addressable.
const sources = {
  'UnicodeData.txt':
    'ff58e5823bd095166564a006e47d111130813dcf8bf234ef79fa51a870edb48f',
  'PropList.txt':
    '53d614508e2a0b2305a8aa21cd60d993de9326cdf65993660dfcce4503548583',
  'DerivedCoreProperties.txt':
    '39d35161f2954497f69e08bdb9e701493f476a3d30222de20028feda36c1dabd',
};
const outputFile = new URL(
  '../crates/artifree-domain/src/data_unicode.rs',
  import.meta.url,
);
const outputSha256 =
  '9b71705e868bce45ed05788352edb65fd62e1d8cfe417ec77e0f6be1a77eff0d';
if (process.argv.length === 3 && process.argv[2] === '--check') {
  assert.equal(
    createHash('sha256')
      .update(await readFile(outputFile))
      .digest('hex'),
    outputSha256,
    'Unicode 16.0.0 table differs from the pinned generation',
  );
  process.exit(0);
}
assert.equal(
  process.argv.length,
  3,
  'Usage: node scripts/generate-data-unicode.mjs <Unicode-16.0.0-directory>',
);
const directory = resolve(process.argv[2]);
const input = {};
for (const [name, hash] of Object.entries(sources)) {
  const bytes = await readFile(resolve(directory, name));
  assert.equal(createHash('sha256').update(bytes).digest('hex'), hash, name);
  input[name] = bytes.toString('utf8');
}
const allowed = new Uint8Array(0x110000);
let first;
for (const line of input['UnicodeData.txt'].trim().split('\n')) {
  const [hex, name, category] = line.split(';');
  const point = Number.parseInt(hex, 16);
  if (name.endsWith(', First>')) first = point;
  const start = name.endsWith(', Last>') ? first : point;
  assert.ok(start !== undefined, 'UnicodeData range without First');
  if (/^[LMNS]/.test(category)) allowed.fill(1, start, point + 1);
}
for (const name of ['PropList.txt', 'DerivedCoreProperties.txt']) {
  for (const line of input[name].split('\n')) {
    const [range, property] = line
      .split('#')[0]
      .split(';')
      .map((part) => part.trim());
    if (
      ![
        'White_Space',
        'Default_Ignorable_Code_Point',
        'Noncharacter_Code_Point',
      ].includes(property)
    )
      continue;
    const [start, end = start] = range
      .split('..')
      .map((hex) => Number.parseInt(hex, 16));
    allowed.fill(0, start, end + 1);
  }
}
allowed.fill(0, 0, 128);
for (const point of [0x2044, 0x2215, 0x29f8, 0xff0f, 0xff3c, 0xfe68])
  allowed[point] = 0;
const ranges = [];
for (let point = 128; point < allowed.length; point++) {
  if (!allowed[point]) continue;
  const start = point;
  while (allowed[point + 1]) point++;
  ranges.push(
    `    (0x${start.toString(16).toUpperCase()}, 0x${point.toString(16).toUpperCase()}),`,
  );
}
const output = `//! Unicode 16.0.0 non-ASCII application-data path characters (decision 0046).
//! Generated by scripts/generate-data-unicode.mjs; do not edit by hand.
//! Source: <https://www.unicode.org/Public/16.0.0/ucd/>
//! Unicode data license: \`THIRD_PARTY_NOTICES.md\`.

/// Sorted disjoint inclusive scalar ranges after category and exclusion rules.
pub(super) const RANGES: &[(u32, u32)] = &[
${ranges.join('\n')}
];
`;
assert.equal(
  createHash('sha256').update(output).digest('hex'),
  outputSha256,
  'Unicode table generation changed; review the specification and generator before updating the digest',
);
await writeFile(outputFile, output);
